/// Reviewed administration surface, not permission inferred from a method name.
///
/// The gateway must resolve a definition from this compiled catalog, require
/// advertised public method metadata, validate its schema and apply its risk.
/// An entry with [AdminOperationDefinition.blockedReason] is discoverable but
/// cannot be executed through the schema-driven administration surface.
enum AdminDomain {
  dashboard,
  storage,
  datasets,
  shares,
  dataProtection,
  network,
  credentials,
  apps,
  containers,
  virtualization,
  reporting,
  system,
  alerts,
  jobs,
  enterprise,
}

