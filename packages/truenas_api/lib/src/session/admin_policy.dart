enum AdminRisk { read, change, destructive, disruptive }

final class AdminOperationDefinition {
  const AdminOperationDefinition({
    required this.id,
    required this.domain,
    required this.title,
    required this.method,
    required this.risk,
    required this.description,
    this.warning,
    this.blockedReason,
  });

  const AdminOperationDefinition.read(
    this.domain,
    this.method,
    this.title,
    this.description, {
    this.blockedReason,
  }) : id = method,
       risk = AdminRisk.read,
       warning = null;

  const AdminOperationDefinition.change(
    this.domain,
    this.method,
    this.title,
    this.description, {
    required this.warning,
    this.blockedReason,
  }) : id = method,
       risk = AdminRisk.change;

  const AdminOperationDefinition.destructive(
    this.domain,
    this.method,
    this.title,
    this.description, {
    required this.warning,
    this.blockedReason,
  }) : id = method,
       risk = AdminRisk.destructive;

  const AdminOperationDefinition.disruptive(
    this.domain,
    this.method,
    this.title,
    this.description, {
    required this.warning,
    this.blockedReason,
  }) : id = method,
       risk = AdminRisk.disruptive;

  final String id;
  final AdminDomain domain;
  final String title;
  final String method;
  final AdminRisk risk;
  final String description;
  final String? warning;
  final String? blockedReason;

  bool get requiresConfirmation => risk != AdminRisk.read;
  bool get requiresTypedConfirmation =>
      risk == AdminRisk.destructive || risk == AdminRisk.disruptive;
}

